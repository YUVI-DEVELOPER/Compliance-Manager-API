def _draw_footer(canvas: Any, doc: Any, generated_dt: datetime) -> None:
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColorRGB(0.35, 0.38, 0.44)
    canvas.drawString(doc.leftMargin, 0.42 * 72, CONFIDENTIALITY_LABEL)
    canvas.drawCentredString(doc.pagesize[0] / 2, 0.42 * 72, f"Generated {_safe_str(_iso_datetime(generated_dt))}")
    canvas.drawRightString(doc.pagesize[0] - doc.rightMargin, 0.42 * 72, f"Page {canvas.getPageNumber()}")
    canvas.restoreState()


