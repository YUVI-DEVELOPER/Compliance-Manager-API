def _stage_fallback(report_status: str, stage: str) -> str:
    status = _safe_str(report_status, "").upper()
    if stage == "submission" and status in {"DRAFT", "SUPERSEDED"}:
        return "Pending"
    if stage in {"review", "decision"} and status in {"DRAFT", "UNDER_REVIEW", "SUPERSEDED"}:
        return "Pending"
    return "Not captured"


def _value_or_stage(value: Any, report_status: str, stage: str) -> str:
    text = _safe_str(value, "")
    return text if text else _stage_fallback(report_status, stage)


def _datetime_or_stage(value: Any, report_status: str, stage: str) -> str:
    text = _format_datetime(value)
    return text if text != "N/A" else _stage_fallback(report_status, stage)


def _risk_level_for_rating(rating: Any, score: int) -> str:
    normalized = _safe_str(rating, "").upper()
    if normalized == "COMPLIANT":
        return "Low"
    if normalized == "MINOR_FINDINGS":
        return "Moderate"
    if normalized == "MAJOR_FINDINGS":
        return "High"
    if normalized == "CRITICAL_RISK":
        return "Critical"
    if score >= 90:
        return "Low"
    if score >= 75:
        return "Moderate"
    if score >= 60:
        return "High"
    return "Critical"


