async def build_audit_review_report_pdf(db: AsyncSession, report_id: uuid.UUID) -> AuditReviewPdfDownload:
    context = await _load_export_context(
        db,
        report_id,
        allowed_statuses=DOWNLOADABLE_REPORT_STATUSES,
        status_error_message="Only approved audit review reports can be downloaded.",
    )
    report = context["report"]
    stored_pdf_is_current = _stored_pdf_uses_current_template(report)
    if report.report_status == FINAL_REPORT_STATUS and stored_pdf_is_current and (report.final_pdf_path or report.final_pdf_hash):
        final_content = _read_final_pdf_bytes(report)
        if final_content is not None:
            return AuditReviewPdfDownload(
                file_name=context["file_name"],
                media_type=PDF_MEDIA_TYPE,
                content=final_content,
            )
        if report.is_locked:
            raise AuditReviewValidationError(
                "Locked approved report final PDF is unavailable and cannot be regenerated automatically.",
                data={"report_id": str(report.report_id), "final_pdf_path": report.final_pdf_path},
            )

    content = _build_pdf_bytes(context)
    if report.report_status == FINAL_REPORT_STATUS:
        await _persist_final_pdf(
            db,
            report,
            file_name=context["file_name"],
            content=content,
            refresh_template=not stored_pdf_is_current,
        )

    return AuditReviewPdfDownload(
        file_name=context["file_name"],
        media_type=PDF_MEDIA_TYPE,
        content=content,
    )


