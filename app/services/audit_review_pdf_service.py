def _severity_counts(findings: list[AuditReviewFinding], report_json: dict[str, Any]) -> dict[str, int]:
    report_summary = _as_dict(report_json.get("finding_summary"))
    if report_summary:
        return {
            "critical": _safe_int(_first_present(report_summary.get("critical"), report_summary.get("CRITICAL"))),
            "high": _safe_int(_first_present(report_summary.get("high"), report_summary.get("HIGH"))),
            "medium": _safe_int(_first_present(report_summary.get("medium"), report_summary.get("MEDIUM"))),
            "low": _safe_int(_first_present(report_summary.get("low"), report_summary.get("LOW"))),
        }

    counter = Counter(_safe_str(finding.severity, "LOW").upper() for finding in findings)
    return {
        "critical": counter.get("CRITICAL", 0),
        "high": counter.get("HIGH", 0),
        "medium": counter.get("MEDIUM", 0),
        "low": counter.get("LOW", 0),
    }


