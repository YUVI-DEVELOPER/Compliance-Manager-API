def _key_finding_rows(findings: list[AuditReviewFinding], report_json: dict[str, Any]) -> list[dict[str, Any]]:
    if findings:
        sorted_findings = sorted(
            findings,
            key=lambda finding: (
                SEVERITY_ORDER.get(_safe_str(finding.severity, "LOW").upper(), 99),
                finding.created_dt,
                str(finding.finding_id),
            ),
        )
        return [
            {
                "severity": _safe_str(finding.severity, "LOW").upper(),
                "check": finding.check_code,
                "title": finding.finding_title or finding.title or finding.check_name,
                "source_record_count": finding.source_record_count,
                "score_impact": finding.score_impact,
                "reviewer_comment": _finding_reviewer_comment(finding.evidence_json or {}),
                "review_status": finding.status,
            }
            for finding in sorted_findings[:KEY_FINDINGS_LIMIT]
        ]

    rows: list[dict[str, Any]] = []
    for item in _as_list(report_json.get("key_findings"))[:KEY_FINDINGS_LIMIT]:
        if not isinstance(item, dict):
            continue
        rows.append(
            {
                "severity": item.get("severity"),
                "check": item.get("check_code"),
                "title": item.get("finding_title"),
                "source_record_count": item.get("source_record_count"),
                "score_impact": item.get("score_impact", "N/A"),
                "reviewer_comment": _finding_reviewer_comment(item),
                "review_status": item.get("review_status") or item.get("status"),
            }
        )
    return rows


def _recommendations(report_json: dict[str, Any], markdown: str | None) -> list[str]:
    structured = [
        _safe_str(item, "")
        for item in _as_list(report_json.get("recommendations"))
        if _safe_str(item, "").strip()
    ]
    if structured:
        return structured

    recommendations: list[str] = []
    in_section = False
    for line in (markdown or "").splitlines():
        stripped = line.strip()
        if stripped.startswith("## "):
            in_section = stripped.lower().startswith("## 6. recommendations")
            continue
        if in_section and stripped.startswith("- "):
            recommendations.append(stripped[2:].strip())
    return recommendations


def _total_penalty(scores: list[AuditReviewScore], analysis_summary: dict[str, Any], overall_score: int) -> int:
    overall_row = next(
        (
            score
            for score in scores
            if score.check_code == OVERALL_CHECK_CODE and score.score_scope == "OVERALL"
        ),
        None,
    )
    if overall_row is not None:
        return _safe_int(overall_row.applied_penalty)
    value = _first_present(analysis_summary.get("total_applied_penalty"), analysis_summary.get("applied_penalty"))
    if value is not None:
        return _safe_int(value)
    return max(0, 100 - overall_score)


