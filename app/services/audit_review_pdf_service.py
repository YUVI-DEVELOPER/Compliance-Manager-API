def _pdf_paragraph(text: Any, style: Any) -> Any:
    from reportlab.platypus import Paragraph

    return Paragraph(escape(_safe_str(text)), style)


def _pdf_table(headers: list[str], rows: list[list[Any]], widths: list[float], styles: dict[str, Any]) -> Any:
    from reportlab.lib import colors
    from reportlab.platypus import Table, TableStyle

    table_rows = [[_pdf_paragraph(header, styles["table_header"]) for header in headers]]
    source_rows = rows or [["N/A" for _ in headers]]
    for row in source_rows:
        padded = [*row, *([""] * max(0, len(headers) - len(row)))]
        table_rows.append([_pdf_paragraph(cell, styles["table_cell"]) for cell in padded[: len(headers)]])

    table = Table(table_rows, colWidths=widths, repeatRows=1, hAlign="LEFT")
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e5e7eb")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#111827")),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#cbd5e1")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    return table


def _pdf_multiline_paragraph(lines: list[str], style: Any) -> Any:
    from reportlab.platypus import Paragraph

    return Paragraph("<br/>".join(escape(_safe_str(line)) for line in lines), style)


