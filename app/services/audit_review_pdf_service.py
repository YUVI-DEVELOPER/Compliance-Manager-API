def _utc_now() -> datetime:
    return datetime.now(UTC)


def _to_utc(value: datetime) -> datetime:
    if value.tzinfo is None or value.tzinfo.utcoffset(value) is None:
        return value.replace(tzinfo=UTC)
    return value.astimezone(UTC)


def _iso_datetime(value: datetime | None) -> str | None:
    if value is None:
        return None
    return _to_utc(value).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _safe_str(value: Any, fallback: str = "N/A") -> str:
    if value is None:
        return fallback
    text = str(value).strip()
    return text or fallback


def _first_present(*values: Any) -> Any:
    for value in values:
        if value is None:
            continue
        if isinstance(value, str) and not value.strip():
            continue
        return value
    return None


def _safe_int(value: Any, fallback: int = 0) -> int:
    try:
        return int(value)
    except (TypeError, ValueError):
        return fallback


def _as_dict(value: Any) -> dict[str, Any]:
    return value if isinstance(value, dict) else {}


def _as_list(value: Any) -> list[Any]:
    return value if isinstance(value, list) else []


def _sanitize_value(value: Any) -> Any:
    if isinstance(value, dict):
        clean: dict[str, Any] = {}
        for key, item in value.items():
            normalized_key = str(key).replace("-", "_").lower()
            if normalized_key in BLOCKED_KEYS:
                continue
            clean[str(key)] = _sanitize_value(item)
        return clean
    if isinstance(value, list):
        return [_sanitize_value(item) for item in value]
    return value


def _format_label(value: Any) -> str:
    text = _safe_str(value)
    if text == "N/A":
        return text
    return " ".join(part if len(part) <= 4 else part.capitalize() for part in re.split(r"[_\s-]+", text) if part)


def _report_status_label(value: Any) -> str:
    status = _safe_str(value, "").upper()
    if status == "UNDER_REVIEW":
        return "SUBMITTED"
    if status == "CHANGES_REQUESTED":
        return "CHANGES REQUESTED"
    return _format_label(status) if status else "N/A"


def _format_datetime(value: Any) -> str:
    if isinstance(value, datetime):
        return _safe_str(_iso_datetime(value))
    if value is None:
        return "N/A"
    return _safe_str(value)


def _format_list(value: Any, fallback: str = "N/A") -> str:
    if isinstance(value, list):
        values = [_safe_str(item, "") for item in value]
        joined = ", ".join(item for item in values if item)
        return joined or fallback
    if isinstance(value, tuple):
        return _format_list(list(value), fallback)
    return _safe_str(value, fallback)


def _display_actor(
    workflow_metadata: dict[str, Any],
    prefix: str,
    *,
    fallback: Any = None,
    unavailable: str = "Not captured",
) -> str:
    actor_type = _safe_str(workflow_metadata.get(f"{prefix}_actor_type"), "").upper()
    name = _safe_str(workflow_metadata.get(f"{prefix}_name"), "")
    email = _safe_str(workflow_metadata.get(f"{prefix}_email"), "")
    user_id = _safe_str(workflow_metadata.get(f"{prefix}_user_id"), "")
    fallback_text = _safe_str(fallback, "")

    if actor_type == ACTOR_TYPE_SYSTEM or name == DEFAULT_SYSTEM_ACTOR or fallback_text == DEFAULT_SYSTEM_ACTOR:
        return "System Scheduler"
    if name and email and name.lower() != email.lower():
        return f"{name} <{email}>"
    if email:
        return email
    if name:
        return name
    if user_id:
        return user_id
    if fallback_text:
        return fallback_text
    return unavailable


