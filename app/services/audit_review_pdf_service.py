def _file_storage_root() -> Path:
    return Path(get_settings().FILE_STORAGE_DIR).resolve()


def _safe_relative_to(path: Path, root: Path) -> str:
    resolved = path.resolve()
    root = root.resolve()
    try:
        return resolved.relative_to(root).as_posix()
    except ValueError as exc:
        raise AuditReviewValidationError("Final PDF path is outside configured file storage.") from exc


def _final_pdf_storage_path(report: AuditReviewReport, file_name: str) -> tuple[Path, str]:
    storage_root = _file_storage_root()
    target_dir = storage_root / "audit_review_reports" / "final" / str(report.report_id)
    target_dir.mkdir(parents=True, exist_ok=True)
    target_path = (target_dir / Path(file_name).name).resolve()
    relative_path = _safe_relative_to(target_path, storage_root)
    return target_path, f"filestorage/{relative_path}"


def _resolve_final_pdf_path(value: str | None) -> Path | None:
    text = _safe_str(value, "")
    if not text:
        return None
    normalized = text.replace("\\", "/").lstrip("/")
    if normalized.startswith("filestorage/"):
        normalized = normalized.removeprefix("filestorage/")
    candidate = (_file_storage_root() / normalized).resolve()
    _safe_relative_to(candidate, _file_storage_root())
    return candidate


def _read_final_pdf_bytes(report: AuditReviewReport) -> bytes | None:
    path = _resolve_final_pdf_path(report.final_pdf_path)
    if path is None or not path.is_file():
        return None
    content = path.read_bytes()
    if report.final_pdf_hash:
        digest = hashlib.sha256(content).hexdigest()
        if digest.lower() != report.final_pdf_hash.lower():
            raise AuditReviewValidationError(
                "Stored final PDF integrity check failed.",
                data={"report_id": str(report.report_id)},
            )
    return content


def _stored_pdf_template_revision(report: AuditReviewReport) -> str:
    metadata = _as_dict(report.workflow_metadata_json)
    final_report = _as_dict(metadata.get("final_report"))
    summary = _as_dict(report.report_summary_json)
    return _safe_str(_first_present(final_report.get("pdf_template_revision"), summary.get("pdf_template_revision")), "")


def _stored_pdf_uses_current_template(report: AuditReviewReport) -> bool:
    return _stored_pdf_template_revision(report) == PDF_TEMPLATE_REVISION


async def _persist_final_pdf(
    db: AsyncSession,
    report: AuditReviewReport,
    *,
    file_name: str,
    content: bytes,
    refresh_template: bool = False,
) -> None:
    target_path, stored_path = _final_pdf_storage_path(report, file_name)
    if report.is_locked and report.final_pdf_path and not refresh_template:
        existing = _read_final_pdf_bytes(report)
        if existing is not None:
            return
        raise AuditReviewValidationError(
            "Locked approved report has a final PDF path but the file could not be read.",
            data={"report_id": str(report.report_id), "final_pdf_path": report.final_pdf_path},
        )

    target_path.write_bytes(content)
    digest = hashlib.sha256(content).hexdigest()
    report.final_pdf_path = stored_path
    report.final_pdf_hash = digest
    report.file_path = report.file_path or stored_path
    report.report_version = report.report_version or get_audit_review_workflow_config().report_version
    workflow_metadata = update_final_pdf_metadata(
        report.workflow_metadata_json,
        final_pdf_path=stored_path,
        final_pdf_hash=digest,
        report_version=report.report_version,
    )
    final_report = dict(_as_dict(workflow_metadata.get("final_report")))
    final_report["pdf_template_revision"] = PDF_TEMPLATE_REVISION
    workflow_metadata["final_report"] = final_report
    report.workflow_metadata_json = workflow_metadata
    summary = dict(report.report_summary_json or {})
    summary["final_pdf_path"] = stored_path
    summary["final_pdf_hash"] = digest
    summary["report_version"] = report.report_version
    summary["pdf_template_revision"] = PDF_TEMPLATE_REVISION
    report.report_summary_json = summary
    report.modified_dt = _utc_now()
    await db.commit()


